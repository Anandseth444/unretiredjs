"""
Update script for RetireJS vulnerability database.

Fetches latest JavaScript vulnerability data from RetireJS upstream repository,
transforms it into a Python-compatible structure, applies persistent custom CVE
enrichments and extractor patches, and writes to vulnerabilities.py.
"""

import argparse
import ast
import datetime
import json
import logging
import os
import pprint
import re
from typing import Any, Dict, List, Optional, Set, Tuple

import requests

logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")
logger = logging.getLogger(__name__)

RETIREJS_URL = "https://raw.githubusercontent.com/RetireJS/retire.js/master/repository/jsrepository.json"
VERSION_PLACEHOLDER_REGEX = r"§§version§§"
VERSION_REPLACEMENT_REGEX = r"[0-9][0-9.a-z_-]+"
DEFAULT_VULNERABILITIES_FILEPATH = os.path.join(os.path.dirname(__file__), "vulnerabilities.py")

CRITICAL_COMPONENT_FIELDS: Set[str] = {"vulnerabilities", "extractors"}
KNOWN_COMPONENT_FIELDS: Set[str] = {"bowername", "npmname", "basePurl", "vulnerabilities", "extractors", "comment", "github"}
KNOWN_VULNERABILITY_FIELDS: Set[str] = {"below", "atOrAbove", "severity", "info", "identifiers", "cwe"}
KNOWN_IDENTIFIER_FIELDS: Set[str] = {"summary", "bug", "issue", "release", "osvdb", "CVE", "retid", "githubID", "PR", "gist", "blog", "tenable"}
KNOWN_EXTRACTOR_FIELDS: Set[str] = {"func", "hashes", "filename", "filecontent", "uri", "filecontentreplace"}


# ==============================================================================
# Persistent Custom Overrides
# Applied cleanly on top of upstream data; preserved on every automated sync.
# ==============================================================================

# Map githubID -> list of CVEs (when upstream RetireJS lacks the CVE identifier)
CUSTOM_CVE_OVERRIDES: Dict[str, List[str]] = {
    # Next.js Image Optimization RCE (librsvg UAF memory flaw via crafted SVG files)
    "GHSA-2464-fhr4-w9xw": ["CVE-2026-96889"],
}

# Custom extractor regex overrides: component -> extractor_type -> {old_pattern: new_pattern}
CUSTOM_EXTRACTOR_OVERRIDES: Dict[str, Dict[str, Dict[str, str]]] = {
    "bootstrap": {
        "uri": {
            r"/([0-9][0-9.a-z_-]+)/js/bootstrap(\.min)?\.js": r"/([0-9]+\.[0-9.a-z_-]+)/js/bootstrap(\.min)?\.js",
        }
    }
}

# Standalone custom components to merge (if not present upstream)
CUSTOM_COMPONENTS: Dict[str, Dict[str, Any]] = {}


def fetch_retirejs_data(url: str = RETIREJS_URL) -> Optional[Dict[str, Any]]:
    """Fetch vulnerability data from the RetireJS upstream repository."""
    logger.info(f"Fetching RetireJS data from: {url}")
    try:
        response = requests.get(url, timeout=30)
        response.raise_for_status()
        return response.json()
    except (requests.RequestException, json.JSONDecodeError) as e:
        logger.error(f"Failed to fetch data from {url}: {e}")
        return None


def load_existing_vulnerabilities(filepath: str = DEFAULT_VULNERABILITIES_FILEPATH) -> Dict[str, Any]:
    """Load existing definitions dictionary from vulnerabilities.py."""
    if not os.path.exists(filepath):
        logger.warning(f"Vulnerability file '{filepath}' not found.")
        return {}

    try:
        with open(filepath, "r", encoding="utf-8") as f:
            content = f.read()
        if "definitions = " in content:
            dict_str = content.split("definitions = ", 1)[1]
            return ast.literal_eval(dict_str)
    except Exception as e:
        logger.error(f"Error loading existing vulnerabilities from '{filepath}': {e}")
    return {}


def write_updated_vulnerabilities(definitions_to_write: Dict[str, Any], filepath: str = DEFAULT_VULNERABILITIES_FILEPATH) -> bool:
    """
    Write definitions to vulnerabilities.py formatted as valid Python literals.
    Parseable by both standard Python import and ast.literal_eval.
    """
    logger.info(f"Writing updated definitions to '{filepath}'...")
    try:
        formatted_defs = pprint.pformat(definitions_to_write, indent=4, width=120, sort_dicts=True)
        header = (
            "# -*- coding: utf-8 -*-\n"
            "# Automatically generated by update_vulnerabilities.py - DO NOT EDIT DIRECTLY.\n"
            "# To add custom CVEs or rules, update CUSTOM_CVE_OVERRIDES in update_vulnerabilities.py.\n\n"
        )
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(header)
            f.write("definitions = ")
            f.write(formatted_defs)
            f.write("\n")

        # Verify output parses cleanly with ast.literal_eval
        with open(filepath, "r", encoding="utf-8") as f:
            dict_str = f.read().split("definitions = ", 1)[1]
            ast.literal_eval(dict_str)

        logger.info(f"Successfully wrote and verified '{filepath}'.")
        return True
    except Exception as e:
        logger.error(f"Error writing definitions to '{filepath}': {e}")
        return False


def transform_vulnerabilities(vulns: Any, component_name: str) -> List[Dict[str, Any]]:
    """Transform and normalize component vulnerability entries."""
    if not isinstance(vulns, list):
        return []

    result = []
    for vuln in vulns:
        if not isinstance(vuln, dict):
            continue

        item: Dict[str, Any] = {}
        for field in KNOWN_VULNERABILITY_FIELDS:
            if field in vuln:
                val = vuln[field]
                item[field] = sorted(list(set(val))) if field == "info" and isinstance(val, list) else val

        if "identifiers" in vuln and isinstance(vuln["identifiers"], dict):
            ident: Dict[str, Any] = {}
            for k, v in vuln["identifiers"].items():
                if k == "CVE":
                    cve_list = [v] if isinstance(v, str) else (v if isinstance(v, list) else [])
                    ident["CVE"] = sorted(list(set(cve_list)))
                else:
                    ident[k] = v
            item["identifiers"] = ident

        # Preserve any unexpected fields
        for k, v in vuln.items():
            if k not in item:
                item[k] = v

        result.append(item)
    return result


def transform_extractors(extractors: Any, component_name: str) -> Dict[str, Any]:
    """Compile version placeholder regexes in extractors."""
    if not isinstance(extractors, dict):
        return {}

    result: Dict[str, Any] = {}
    for field in KNOWN_EXTRACTOR_FIELDS:
        if field not in extractors:
            continue

        if field in ("filename", "filecontent", "uri"):
            patterns = extractors[field]
            if isinstance(patterns, list):
                result[field] = sorted(list(set(
                    re.sub(VERSION_PLACEHOLDER_REGEX, VERSION_REPLACEMENT_REGEX, p)
                    for p in patterns if isinstance(p, str)
                )))
        elif field == "filecontentreplace":
            replaces = []
            for item in extractors[field]:
                if not item or len(item) < 3:
                    replaces.append(item)
                    continue
                delimiter = item[0]
                parts = item[1:].split(delimiter)
                if len(parts) >= 2:
                    pattern = re.sub(VERSION_PLACEHOLDER_REGEX, VERSION_REPLACEMENT_REGEX, parts[0])
                    replacement = parts[1]
                    reconstructed = f"{delimiter}{pattern}{delimiter}{replacement}"
                    if len(parts) > 2:
                        reconstructed += f"{delimiter}{delimiter.join(parts[2:])}"
                    elif item.endswith(delimiter) and not reconstructed.endswith(delimiter):
                        reconstructed += delimiter
                    replaces.append(reconstructed)
                else:
                    replaces.append(item)
            result[field] = sorted(list(set(replaces)))
        elif field in ("func", "hashes"):
            result[field] = extractors[field]

    for k, v in extractors.items():
        if k not in result:
            result[k] = v

    return result


def transform_component(component_name: str, raw_data: Dict[str, Any]) -> Dict[str, Any]:
    """Transform a raw RetireJS component dictionary."""
    data: Dict[str, Any] = {}
    for field in KNOWN_COMPONENT_FIELDS:
        if field in raw_data:
            if field == "bowername":
                bower = raw_data[field]
                data[field] = sorted(list(set([bower] if isinstance(bower, str) else (bower if isinstance(bower, list) else []))))
            elif field == "vulnerabilities":
                data[field] = transform_vulnerabilities(raw_data.get(field, []), component_name)
            elif field == "extractors":
                data[field] = transform_extractors(raw_data.get(field, {}), component_name)
            else:
                data[field] = raw_data[field]

    for k, v in raw_data.items():
        if k not in KNOWN_COMPONENT_FIELDS and k not in data:
            data[k] = v

    data.setdefault("vulnerabilities", [])
    data.setdefault("extractors", {})
    return data


def apply_custom_enrichments(definitions: Dict[str, Any]) -> Tuple[Dict[str, Any], int]:
    """
    Apply persistent custom enrichments and overrides:
    - Enriches vulnerabilities with CVEs missing in upstream RetireJS.
    - Patches known extractor regex flaws.
    - Injects custom components if defined.
    """
    count = 0

    # 1. Enrich missing CVEs by githubID
    for comp_data in definitions.values():
        for vuln in comp_data.get("vulnerabilities", []):
            identifiers = vuln.setdefault("identifiers", {})
            github_id = identifiers.get("githubID")
            if github_id and github_id in CUSTOM_CVE_OVERRIDES:
                existing = set(identifiers.get("CVE", []))
                enriched = sorted(existing | set(CUSTOM_CVE_OVERRIDES[github_id]))
                if enriched != identifiers.get("CVE"):
                    identifiers["CVE"] = enriched
                    count += 1

    # 2. Patch extractor regexes
    for comp_name, extractors in CUSTOM_EXTRACTOR_OVERRIDES.items():
        if comp_name not in definitions:
            continue
        comp_extractors = definitions[comp_name].setdefault("extractors", {})
        for ext_type, replacements in extractors.items():
            patterns = comp_extractors.get(ext_type, [])
            if isinstance(patterns, list):
                comp_extractors[ext_type] = [replacements.get(p, p) for p in patterns]
                count += len(replacements)

    # 3. Add custom standalone components
    for comp_name, comp_data in CUSTOM_COMPONENTS.items():
        if comp_name not in definitions:
            definitions[comp_name] = comp_data
            count += 1

    return definitions, count


def normalize_component(comp: Dict[str, Any]) -> Dict[str, Any]:
    """Normalize component structure for deterministic comparison."""
    norm: Dict[str, Any] = {}
    if "vulnerabilities" in comp:
        norm["vulnerabilities"] = sorted(
            comp["vulnerabilities"],
            key=lambda x: json.dumps(x.get("identifiers", {}), sort_keys=True)
        )
    if "extractors" in comp:
        norm["extractors"] = {
            k: sorted(v) if isinstance(v, list) else v
            for k, v in sorted(comp["extractors"].items())
        }
    for k in sorted(comp.keys()):
        if k not in ("vulnerabilities", "extractors"):
            val = comp[k]
            norm[k] = sorted(val) if isinstance(val, list) else val
    return norm


def are_definitions_different(old_defs: Dict[str, Any], new_defs: Dict[str, Any]) -> bool:
    """Compare old and new definitions for substantive changes."""
    if set(old_defs.keys()) != set(new_defs.keys()):
        return True
    return any(normalize_component(old_defs.get(k, {})) != normalize_component(new_defs[k]) for k in new_defs)


def run_sync(filepath: str = DEFAULT_VULNERABILITIES_FILEPATH, force: bool = False) -> bool:
    """Run full synchronization from RetireJS upstream to local vulnerabilities.py."""
    existing_definitions = load_existing_vulnerabilities(filepath)
    fetched_data = fetch_retirejs_data()
    if not fetched_data:
        return False

    new_definitions = {
        name: transform_component(name, data)
        for name, data in fetched_data.items()
        if isinstance(data, dict)
    }

    enriched_definitions, applied_count = apply_custom_enrichments(new_definitions)
    logger.info(f"Applied {applied_count} custom enrichments/patches.")

    old_vulns = sum(len(c.get("vulnerabilities", [])) for c in existing_definitions.values())
    new_vulns = sum(len(c.get("vulnerabilities", [])) for c in enriched_definitions.values())
    logger.info(f"Vulnerabilities: {old_vulns} -> {new_vulns} (net change: +{new_vulns - old_vulns})")

    if force or are_definitions_different(existing_definitions, enriched_definitions):
        return write_updated_vulnerabilities(enriched_definitions, filepath)

    logger.info("No changes detected in vulnerability definitions. Skipping file update.")
    return True


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Sync RetireJS vulnerability definitions.")
    parser.add_argument("--filepath", default=DEFAULT_VULNERABILITIES_FILEPATH, help="Path to vulnerabilities.py")
    parser.add_argument("--force", action="store_true", help="Force write even if no detected changes")
    args = parser.parse_args()

    run_sync(filepath=args.filepath, force=args.force)
